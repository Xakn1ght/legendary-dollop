export function faNum(v, lang) {
  return lang === 'fa' ? String(v).replace(/\d/g, (d) => '۰۱۲۳۴۵۶۷۸۹'[d]) : String(v);
}

// coupon_type → human label (payload keys: discount_percent, gb, plan_gb)
export function couponLabel(c, tt, lang) {
  const p = c.payload || {};
  if (c.coupon_type === 'discount_percent') {
    const n = Number(p.discount_percent || 0);
    return lang === 'fa' ? `٪${faNum(n, lang)} تخفیف` : `${n}% discount`;
  }
  if (c.coupon_type === 'free_gb') {
    const n = Number(p.gb || 0);
    return lang === 'fa' ? `${faNum(n, lang)} گیگ رایگان` : `${n}GB free`;
  }
  if (c.coupon_type === 'free_plan') {
    const n = Number(p.plan_gb || 0);
    return lang === 'fa' ? `پلن ${faNum(n, lang)} گیگ رایگان` : `Free ${n}GB plan`;
  }
  if (c.coupon_type === 'free_autorenew') return tt('couponFreeAutorenew');
  if (c.coupon_type === 'vip_days') {
    const d = Number(p.days || 30);
    return lang === 'fa' ? `${faNum(d, lang)} روز VIP رایگان` : `${d} days of free VIP`;
  }
  return c.coupon_type;
}
